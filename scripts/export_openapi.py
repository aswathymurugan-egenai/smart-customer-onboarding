"""Write the OpenAPI 3.1 document that `create_app()` generates to `contracts/openapi.yaml`.

Run `python -m scripts.export_openapi` to regenerate, or add `--check` to fail when the
committed file differs from what the code produces.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml
from pydantic import SecretStr

from app.config import Settings
from app.main import create_app

TARGET = Path(__file__).resolve().parents[1] / "contracts" / "openapi.yaml"
TOP_LEVEL_ORDER = ("openapi", "info", "servers", "tags", "paths", "components")
HEADER = "# Generated by scripts/export_openapi.py from the FastAPI app. Do not edit by hand.\n"


def spec_settings() -> Settings:
    """Settings that build the app without credentials. The spec does not depend on them."""
    return Settings(
        _env_file=None,
        customer_store="memory",
        allow_local_adapters=True,
        cors_allow_origins=["http://localhost:3000"],
        pii_hash_key=SecretStr("spec-export-only-key"),
        advisor_enabled=False,
        assistant_enabled=False,
        email_allow_reserved_domains=True,
    )


def generate_schema() -> dict[str, Any]:
    """Return the app's OpenAPI document."""
    return create_app(spec_settings()).openapi()


def render(schema: dict[str, Any]) -> str:
    """Serialize with a fixed top-level order and alphabetically sorted keys below it."""
    chunks = [HEADER]
    keys = [key for key in TOP_LEVEL_ORDER if key in schema]
    keys += sorted(key for key in schema if key not in TOP_LEVEL_ORDER)
    for key in keys:
        chunks.append(
            yaml.safe_dump(
                {key: schema[key]}, sort_keys=True, allow_unicode=True, width=100, indent=2
            )
        )
    return "".join(chunks)


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", type=Path, default=TARGET)
    parser.add_argument("--check", action="store_true", help="fail when the file is out of date")
    args = parser.parse_args(argv)
    rendered = render(generate_schema())
    if args.check:
        if not args.target.exists() or args.target.read_text(encoding="utf-8") != rendered:
            print(f"{args.target} is out of date. Run: python -m scripts.export_openapi")
            return 1
        print(f"{args.target} is current")
        return 0
    args.target.parent.mkdir(parents=True, exist_ok=True)
    args.target.write_text(rendered, encoding="utf-8")
    print(f"wrote {args.target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
